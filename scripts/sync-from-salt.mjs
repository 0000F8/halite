#!/usr/bin/env node
// Refreshes css/ and react/ from Salt's app (the source of truth).
//   node scripts/sync-from-salt.mjs [path/to/salt-fe]
// Reads src/ui/halite/{halite.css,index.jsx} and src/ui/tokens.js, resolves the
// --salt-* tokens for light and dark so css/halite.css stands alone, and builds
// react/index.js with esbuild.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const fe = path.resolve(process.argv[2] || path.join(os.homedir(), "projects/salt/salt-fe"));
const src = path.join(fe, "src/ui");

// tokens.js is ESM in a CJS-typed package: import a copy with an .mjs name.
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "halite-"));
fs.copyFileSync(path.join(src, "tokens.js"), path.join(tmp, "tokens.mjs"));
const { TOKEN_MAP } = await import(pathToFileURL(path.join(tmp, "tokens.mjs")).href);

// The two palettes the tokens read (Salt's theme: trust-blue, radius 0).
const palettes = {
  light: {
    mode: "light",
    primary: { main: "#2563EB", contrastText: "#FFFFFF" },
    background: { default: "#F8FAFC", paper: "#FFFFFF" },
    text: { primary: "#0F172A", secondary: "#64748B" },
    divider: "rgba(15, 23, 42, 0.10)",
    grey: { 100: "#F1F5F9", 800: "#1E293B" },
  },
  dark: {
    mode: "dark",
    primary: { main: "#60A5FA", contrastText: "#0A1A33" },
    background: { default: "#0B1220", paper: "#141C2E" },
    text: { primary: "#F1F5F9", secondary: "#94A3B8" },
    divider: "rgba(241, 245, 249, 0.10)",
    grey: { 100: "#F1F5F9", 800: "#1E293B" },
  },
};
const resolve = (mode) => {
  const theme = { palette: palettes[mode], shape: { borderRadius: 0 } };
  const out = {};
  for (const [name, fn] of Object.entries(TOKEN_MAP)) {
    try { out[name] = fn(theme); } catch { /* layers etc: not used by the kit */ }
  }
  return out;
};

let css = fs.readFileSync(path.join(src, "halite/halite.css"), "utf8");
const used = new Set([...css.matchAll(/--salt-[a-z-]+/g)].map((m) => m[0]));
const block = (vars) => [...used].filter((n) => vars[n] != null).map((n) => `  ${n}:${vars[n]};`).join("\n");
const light = resolve("light");
const dark = resolve("dark");

// Standalone fix: ".h-root button{color:inherit}" (0,1,1) out-ranks ".h-button"
// (0,1,0), so inside a plain-HTML .h-root every button lost its own colour
// (white-on-blue read navy-on-blue). Zero-specificity resets let classes win.
css = css
  .replace(".h-root button,.h-root input,.h-root textarea{", ":where(.h-root) :where(button,input,textarea){")
  .replace(".h-root button{cursor", ":where(.h-root) :where(button){cursor");

// Strip the in-app header comment; the standalone file gets its own.
css = css.replace(/^\/\*[\s\S]*?\*\/\s*/, "");

const header = `/* Halite: the design system behind Salt. Framework-free; plain HTML works.
   Generated by scripts/sync-from-salt.mjs from Salt's app: do not edit here.
   Wrap your page (or a section) in class "h-root". Theme: follows
   prefers-color-scheme; force one with <html data-theme="light|dark">.
   Fonts: IBM Plex Sans / Plex Mono are referenced, not bundled (see README). */
:root{
${block(light)}
  --h-font:'IBM Plex Sans',system-ui,-apple-system,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;
}
@media (prefers-color-scheme:dark){
  :root:not([data-theme="light"]){
${block(dark).replace(/^ /gm, "   ")}
  }
}
:root[data-theme="dark"]{
${block(dark)}
}
.h-root{background:var(--salt-bg);color:var(--salt-ink);font-family:var(--h-font);-webkit-font-smoothing:antialiased}
`;
fs.writeFileSync(path.join(root, "css/halite.css"), header + css);

// React: the kit's own index.jsx without the stylesheet import.
const jsx = fs.readFileSync(path.join(src, "halite/index.jsx"), "utf8").replace(/^import "\.\/halite\.css";\n/m, "");
const entry = path.join(tmp, "index.jsx");
fs.writeFileSync(entry, jsx);
await build({
  entryPoints: [entry],
  outfile: path.join(root, "react/index.js"),
  format: "esm",
  bundle: true,
  packages: "external",
  jsx: "transform",
  loader: { ".jsx": "jsx" },
  target: "es2020",
});
const out = path.join(root, "react/index.js");
fs.writeFileSync(out, fs.readFileSync(out, "utf8").replace(/^\/\/ .*\n/, ""));
console.log("synced from", fe);
